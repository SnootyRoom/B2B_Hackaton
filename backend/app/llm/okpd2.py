def codes_for(categories: list[str]) -> list[str]:
    """Коды выбранных категорий без повторов, в порядке справочника. Неизвестные — пропускаются."""
    seen: dict[str, None] = {}
    for name in categories:
        for code in OKPD2_CATEGORIES.get(name, ()):
            seen.setdefault(code, None)
    return list(seen)
